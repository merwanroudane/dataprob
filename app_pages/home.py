def _render_stage(frame: int) -> None:
    for offset, row in ((0, STAGES[:5]), (5, STAGES[5:])):
        cols = st.columns(5, gap="small")
        for i, (title, _desc, color) in enumerate(row):
            idx = offset + i
            with cols[i]:
                with st.container(border=True, height=120):
                    if idx == frame:
                        st.markdown(f"**:{color}-badge[{title}]**")
                        st.markdown(":material/play_arrow: **المرحلة الحالية**")
                    elif idx < frame:
                        st.markdown(f":gray[{title}]")
                        st.markdown(":material/check_circle: :green[تمّت]")
                    else:
                        st.markdown(f":gray[{title}]")
                        st.caption("في الانتظار")

    st.progress((frame + 1) / len(STAGES), text=f"المرحلة {frame + 1} من {len(STAGES)}")
    title, desc, color = STAGES[frame]
    with st.container(border=True):
        st.markdown(f"##### :{color}-badge[{title}]")
        st.markdown(desc)


